import sanitizeHtml from 'sanitize-html';

export function rawHtmlSanitize(dirty: string): string {
  return sanitizeHtml(dirty, {
    allowedTags: sanitizeHtml.defaults.allowedTags.concat([
      'img',
      'h1',
      'h2',
      'h3',
      'h4',
      'h5',
      'h6',
      'iframe',
      'span',
      'u',
      's',
      'sub',
      'sup',
      'mark',
      'figure',
      'figcaption',
      'picture',
      'source',
      'video',
      'audio',
      'table',
      'thead',
      'tbody',
      'tfoot',
      'tr',
      'th',
      'td',
      'colgroup',
      'col',
      'caption',
      'div',
      'p',
      'br',
      'hr',
      'a',
      'strong',
      'b',
      'i',
      'em',
      'ul',
      'ol',
      'li',
      'blockquote',
      'pre',
      'code',
    ]),
    allowedAttributes: {
      '*': ['class', 'id', 'style', 'dir', 'lang', 'title', 'align'],
      a: ['href', 'name', 'target', 'rel'],
      img: ['src', 'srcset', 'alt', 'title', 'width', 'height', 'loading'],
      iframe: ['src', 'width', 'height', 'frameborder', 'allowfullscreen', 'allow'],
      source: ['src', 'type', 'srcset', 'media'],
      video: ['src', 'width', 'height', 'controls', 'autoplay', 'loop', 'muted', 'poster'],
      audio: ['src', 'controls', 'autoplay', 'loop', 'muted'],
      td: ['colspan', 'rowspan', 'width', 'height'],
      th: ['colspan', 'rowspan', 'width', 'height'],
      table: ['border', 'cellpadding', 'cellspacing', 'width', 'height'],
      col: ['span', 'width'],
      colgroup: ['span', 'width'],
    },
    allowedStyles: {
      '*': {
        // Typography
        'text-align': [/^.*$/],
        'font-size': [/^.*$/],
        'font-family': [/^.*$/],
        'font-weight': [/^.*$/],
        'font-style': [/^.*$/],
        'line-height': [/^.*$/],
        'text-decoration': [/^.*$/],
        color: [/^.*$/],
        // Backgrounds
        background: [/^.*$/],
        'background-color': [/^.*$/],
        // Spacing & Sizing
        margin: [/^.*$/],
        'margin-top': [/^.*$/],
        'margin-right': [/^.*$/],
        'margin-bottom': [/^.*$/],
        'margin-left': [/^.*$/],
        padding: [/^.*$/],
        'padding-top': [/^.*$/],
        'padding-right': [/^.*$/],
        'padding-bottom': [/^.*$/],
        'padding-left': [/^.*$/],
        width: [/^.*$/],
        height: [/^.*$/],
        'max-width': [/^.*$/],
        'max-height': [/^.*$/],
        'min-width': [/^.*$/],
        'min-height': [/^.*$/],
        // Layout
        display: [/^.*$/],
        float: [/^.*$/],
        clear: [/^.*$/],
        position: [/^.*$/],
        top: [/^.*$/],
        right: [/^.*$/],
        bottom: [/^.*$/],
        left: [/^.*$/],
        'z-index': [/^.*$/],
        // Borders
        border: [/^.*$/],
        'border-width': [/^.*$/],
        'border-style': [/^.*$/],
        'border-color': [/^.*$/],
        'border-radius': [/^.*$/],
        'border-collapse': [/^.*$/],
        'border-top': [/^.*$/],
        'border-right': [/^.*$/],
        'border-bottom': [/^.*$/],
        'border-left': [/^.*$/],
        'border-top-width': [/^.*$/],
        'border-right-width': [/^.*$/],
        'border-bottom-width': [/^.*$/],
        'border-left-width': [/^.*$/],
        'border-top-style': [/^.*$/],
        'border-right-style': [/^.*$/],
        'border-bottom-style': [/^.*$/],
        'border-left-style': [/^.*$/],
        'border-top-color': [/^.*$/],
        'border-right-color': [/^.*$/],
        'border-bottom-color': [/^.*$/],
        'border-left-color': [/^.*$/],
        // Lists
        'list-style-type': [/^.*$/],
        'list-style-position': [/^.*$/],
        'list-style': [/^.*$/],
        // Others
        'vertical-align': [/^.*$/],
        'box-sizing': [/^.*$/],
        overflow: [/^.*$/],
        'overflow-x': [/^.*$/],
        'overflow-y': [/^.*$/],
        'white-space': [/^.*$/],
        'word-break': [/^.*$/],
        'word-wrap': [/^.*$/],
      },
    },
    allowedSchemes: [...sanitizeHtml.defaults.allowedSchemes, 'data', 'blob'],
    allowedSchemesAppliedToAttributes: ['href', 'src', 'cite', 'srcset'],
  });
}
